FIXES.sort(key=lambda x: -len(x[0]))


def apply(text: str):
    hits = {}
    for bad, good in FIXES:
        if bad and bad in text:
            hits[bad] = text.count(bad)
            text = text.replace(bad, good)
    return text, hits


total = {}
for name in ("1-纯文字.txt", "2-时间轴.txt", "3-字幕.srt"):
    p = VDIR / name
    src = p.read_text(encoding="utf-8")
    fixed, hits = apply(src)
    for k, v in hits.items():
        total[k] = total.get(k, 0) + v
    out = VDIR / name.replace(".txt", "（校对）.txt").replace(".srt", "（校对）.srt")
    out.write_text(fixed, encoding="utf-8")
    print(f"{name} -> {out.name}  修改 {sum(hits.values())} 处")

print(f"\n共修正 {len(total)} 类、{sum(total.values())} 处")

